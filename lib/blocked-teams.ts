function normalize(text: string): string {
  return (
    ' ' +
    text
      .toLowerCase()
      .replace(/\u2019/g, "'")
      .replace(/&/g, ' and ')
      .replace(/[^a-z0-9/' ]/g, ' ')
      .replace(/\//g, ' ')
      .replace(/'/g, '')
      .replace(/\s+/g, ' ')
      .trim() +
    ' '
  );
}

const PATTERNS: string[] = [...LEAGUE_TERMS, ...TEAM_TERMS].map((t) => ' ' + t + ' ');

export function mentionsProTeam(title: string): boolean {
  const n = normalize(title);
  return PATTERNS.some((p) => n.includes(p));
}
